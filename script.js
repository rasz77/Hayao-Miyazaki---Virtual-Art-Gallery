const buttons = document.getElementById("movie-buttons");
const detail = document.getElementById("movie-detail");

let currentMovie = 0;

// Convert longer text into paragraphs
function formatParagraphs(text) {
  return text.trim().split(/\n\s*\n/).map(paragraph => {
    return `<p>${paragraph.trim()}</p>`;
  }).join("");
}

// Display selected movie
function showMovie(index) {
  currentMovie = (index + movies.length) % movies.length;

  const movie = movies[currentMovie];
  const images = movie.images || [movie.image];

  // Highlight selected movie button
  document.querySelectorAll(".movie-buttons button").forEach((button, i) => {
    button.classList.toggle("active", i === currentMovie);
    button.setAttribute("aria-pressed", String(i === currentMovie));
  });

  // Additional pictures below the main image
  const extraImages = images.slice(1).map((image, i) => `
    <figure class="extra-image">
      <img
        src="images/${image}"
        alt="Additional scene ${i + 1} from ${movie.title}"
        loading="lazy"
      >
    </figure>
  `).join("");

  detail.innerHTML = `
    <!-- LEFT COLUMN: MOVIE IMAGES -->
    <div class="movie-gallery">

      <img
        class="main-movie-image"
        src="images/${images[0]}"
        alt="Main scene from ${movie.title}"
      >


      <div class="extra-movie-images">
        ${extraImages}
      </div>

    </div>

    <!-- RIGHT COLUMN: MOVIE INFORMATION -->
    <div class="movie-info">

      <span class="movie-year">${movie.year}</span>

      <h3>${movie.title}</h3>

      <h4>The Story</h4>
      ${formatParagraphs(movie.description)}

      <h4>Main Characters</h4>
      ${formatParagraphs(movie.characters)}

      <h4>Artistic Themes</h4>
      ${formatParagraphs(movie.themes)}

      <h4>Art and Animation</h4>
      ${formatParagraphs(movie.artwork)}

      <h4>Why This Film Matters</h4>
      ${formatParagraphs(movie.significance)}

      <div class="movie-links">

        <a
          href="${movie.link}"
          target="_blank"
          rel="noopener noreferrer"
          class="movie-link">
          View Official Artwork
        </a>

        <a
          href="https://www.youtube.com/results?search_query=${encodeURIComponent(movie.title + " official trailer")}"
          target="_blank"
          rel="noopener noreferrer"
          class="movie-link">
          Find Official Trailer
        </a>

      </div>

    </div>
  `;

  const counter = document.getElementById("movie-counter");

  if (counter) {
    counter.textContent = `${currentMovie + 1} / ${movies.length}`;
  }
}

// Create the five movie selection buttons
movies.forEach((movie, index) => {
  const button = document.createElement("button");

  button.textContent = movie.title;
  button.type = "button";
  button.setAttribute("aria-pressed", "false");

  button.addEventListener("click", () => {
    showMovie(index);
  });

  buttons.appendChild(button);
});

// Previous movie
function previousMovie() {
  showMovie(currentMovie - 1);
}

// Next movie
function nextMovie() {
  showMovie(currentMovie + 1);
}

// Show first movie when page loads
showMovie(0);